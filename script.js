function saveToStorage() {
    try {
        localStorage.setItem('bill_splitter_state', JSON.stringify(state));
    } catch (e) {
        console.warn('LocalStorage error:', e);
    }
}

function loadFromStorage() {
    try {
        const saved = localStorage.getItem('bill_splitter_state');
        if (saved) {
            const parsed = JSON.parse(saved);
            state = Object.assign(state, parsed);
            if (state.people && Array.isArray(state.people)) {
                state.people.forEach(p => {
                    if (typeof p.amountPaid !== 'number' || isNaN(p.amountPaid)) {
                        p.amountPaid = 0;
                    }
                    if (typeof p.balance !== 'number' || isNaN(p.balance)) {
                        p.balance = 0;
                    }
                    if (typeof p.email !== 'string') {
                        p.email = '';
                    }
                    if (p.userId === undefined) {
                        p.userId = null;
                    }
                });
                deduplicatePeople();
            }
        }
    } catch (e) {
        console.warn('Could not load from localStorage:', e);
    }
}

