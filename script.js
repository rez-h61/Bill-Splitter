async function saveBillToCloud() {
    if (!currentUser) {
        showToast('Please sign in or register to sync your bills with Supabase cloud!', 'error');
        if (authScreen) authScreen.style.display = 'flex';
        if (mainAppContent) mainAppContent.style.display = 'none';
        return;
    }

    if (state.items.length === 0) {
        showToast(t('toast_no_items'), 'error');
        return;
    }

    if (!btnSaveCloud) return;
    const originalText = btnSaveCloud.innerHTML;
    btnSaveCloud.disabled = true;
    btnSaveCloud.innerHTML = `<span>Saving...</span>`;

    try {
        let subtotal = 0;
        state.items.forEach(i => subtotal += i.price);
        const taxTotal = subtotal * (state.extras.taxPercent / 100);
        const serviceTotal = subtotal * (state.extras.servicePercent / 100);
        const discountTotal = Math.min(state.extras.discountAmount || 0, subtotal + taxTotal + serviceTotal);
        const grandTotal = Math.max(0, subtotal + taxTotal + serviceTotal - discountTotal);

        const currentUserName = (currentUser.user_metadata && currentUser.user_metadata.display_name)
            || currentUser.email.split('@')[0];

        const payers = state.people.filter(p => (p.amountPaid || 0) > 0);
        const payerSummary = payers.length > 0 
            ? payers.map(p => `${p.name} (RM ${parseFloat(p.amountPaid).toFixed(2)})`).join(', ')
            : `${currentUserName} (RM ${grandTotal.toFixed(2)})`;

        const transactions = calculateSettlements(grandTotal);

        const billSnapshot = {
            subtotal: subtotal,
            taxPercent: state.extras.taxPercent,
            servicePercent: state.extras.servicePercent,
            discountAmount: state.extras.discountAmount,
            grandTotal: grandTotal,
            payerSummary: payerSummary,
            payers: payers.map(p => ({ name: p.name, amountPaid: p.amountPaid })),
            people: state.people.map(p => ({
                id: p.id,
                name: p.name,
                email: p.email || null,
                subtotal: p.subtotal || 0,
                debt: p.debt || 0,
                amountPaid: p.amountPaid || 0,
                balance: p.balance || 0
            })),
            settlements: transactions.map(tr => ({
                from: tr.from,
                to: tr.to,
                amount: tr.amount
            }))
        };

        // 1. Insert into public.bills (Try with rich columns, fallback if columns not added yet)
        let billData = null;
        const richInsert = await supabaseClient
            .from('bills')
            .insert([{
                created_by: currentUser.id,
                title: `Bill ${new Date().toLocaleDateString()}`,
                total_amount: grandTotal,
                payer_summary: payerSummary,
                bill_data: billSnapshot
            }])
            .select()
            .single();

        if (richInsert.error) {
            console.warn('Columns payer_summary/bill_data not found in bills. Retrying with basic columns:', richInsert.error.message);
            const basicInsert = await supabaseClient
                .from('bills')
                .insert([{
                    created_by: currentUser.id,
                    title: `Bill ${new Date().toLocaleDateString()}`,
                    total_amount: grandTotal
                }])
                .select()
                .single();
            if (basicInsert.error) throw basicInsert.error;
            billData = basicInsert.data;
        } else {
            billData = richInsert.data;
        }

        // 2. Insert into public.bill_items
        if (state.items.length > 0) {
            const billItems = state.items.map(item => {
                const names = item.sharedBy.map(id => {
                    const p = state.people.find(x => x.id === id);
                    return p ? p.name : String(id);
                });
                return {
                    bill_id: billData.id,
                    name: item.name,
                    price: item.price,
                    shared_by: names
                };
            });

            const { error: itemsError } = await supabaseClient
                .from('bill_items')
                .insert(billItems);

            if (itemsError) throw itemsError;
        }

        // 3. Insert Settlement Transfers into public.debts
        if (transactions.length > 0) {
            const currentUserEmail = (currentUser.email || '').toLowerCase().trim();

            const debtsToInsert = transactions.map(tr => {
                const debtorPerson = state.people.find(p => p.id === tr.fromId) ||
                                     state.people.find(p => p.name.toLowerCase().trim() === tr.from.toLowerCase().trim());
                const creditorPerson = state.people.find(p => p.id === tr.toId) ||
                                       state.people.find(p => p.name.toLowerCase().trim() === tr.to.toLowerCase().trim());

                const isDebtorMe = debtorPerson ? (debtorPerson.isCurrentUser || debtorPerson.userId === currentUser.id) : (tr.from.toLowerCase().trim() === currentUserName.toLowerCase().trim());
                const isCreditorMe = creditorPerson ? (creditorPerson.isCurrentUser || creditorPerson.userId === currentUser.id) : (tr.to.toLowerCase().trim() === currentUserName.toLowerCase().trim());

                const debtorEmail = (debtorPerson && debtorPerson.email) ? debtorPerson.email.toLowerCase().trim() : (isDebtorMe ? currentUserEmail : null);
                const creditorEmail = (creditorPerson && creditorPerson.email) ? creditorPerson.email.toLowerCase().trim() : (isCreditorMe ? currentUserEmail : null);

                const debtorId = isDebtorMe ? currentUser.id : (debtorPerson?.userId || null);
                const creditorId = isCreditorMe ? currentUser.id : (creditorPerson?.userId || null);

                // Compute debtor items summary
                let debtorItemsText = '';
                if (debtorPerson) {
                    const debtorItems = state.items.filter(i => i.sharedBy.includes(debtorPerson.id));
                    debtorItemsText = debtorItems.map(i => {
                        const count = i.sharedBy.length || 1;
                        const perShare = i.price / count;
                        return `${i.name} (RM ${perShare.toFixed(2)}${count > 1 ? ` - 1/${count}` : ''})`;
                    }).join(', ');
                }

                return {
                    bill_id: billData.id,
                    debtor_id: debtorId,
                    debtor_name: tr.from,
                    debtor_email: debtorEmail,
                    creditor_id: creditorId,
                    creditor_name: tr.to,
                    creditor_email: creditorEmail,
                    amount: tr.amount,
                    status: 'pending',
                    items_summary: debtorItemsText || null
                };
            });

            const { error: debtsError } = await supabaseClient
                .from('debts')
                .insert(debtsToInsert);

            if (debtsError) {
                // If columns items_summary or emails do not exist yet in Supabase (before ALTER TABLE)
                console.warn('Columns items_summary/emails not found in debts table. Retrying with basic columns:', debtsError.message);
                const fallbackDebts = debtsToInsert.map(d => ({
                    bill_id: d.bill_id,
                    debtor_id: d.debtor_id,
                    debtor_name: d.debtor_name,
                    creditor_id: d.creditor_id,
                    creditor_name: d.creditor_name,
                    amount: d.amount,
                    status: d.status
                }));
                const { error: fallbackErr } = await supabaseClient
                    .from('debts')
                    .insert(fallbackDebts);
                if (fallbackErr) throw fallbackErr;
            }
        }

        showToast(t('toast_bill_saved_cloud'), 'success');
        loadCloudData();
    } catch (err) {
        console.error('Error saving to Supabase:', err);
        showToast(err.message || 'Failed to save bill to cloud.', 'error');
    } finally {
        btnSaveCloud.disabled = false;
        btnSaveCloud.innerHTML = originalText;
    }
}

