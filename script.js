function generateReceiptText() {
    if (state.items.length === 0) return null;

    let subtotal = 0;
    state.items.forEach(i => subtotal += i.price);

    const taxTotal = subtotal * (state.extras.taxPercent / 100);
    const serviceTotal = subtotal * (state.extras.servicePercent / 100);
    const discountTotal = Math.min(state.extras.discountAmount || 0, subtotal + taxTotal + serviceTotal);
    const grandTotal = Math.max(0, subtotal + taxTotal + serviceTotal - discountTotal);

    let text = `${t('receipt_header')}\n`;
    text += `━━━━━━━━━━━━━━━━━━━━━\n`;
    text += `${t('receipt_items_title')}\n`;

    state.items.forEach(item => {
        text += `• ${item.name}: RM ${item.price.toFixed(2)} (${item.sharedBy.length} ${t('pays')})\n`;
    });

    text += `━━━━━━━━━━━━━━━━━━━━━\n`;
    text += `💵 ${t('subtotal')} RM ${subtotal.toFixed(2)}\n`;

    if (taxTotal > 0) {
        text += `📑 ${t('label_tax')} (${state.extras.taxPercent}%): +RM ${taxTotal.toFixed(2)}\n`;
    }
    if (serviceTotal > 0) {
        text += `🛎️ ${t('label_service')} (${state.extras.servicePercent}%): +RM ${serviceTotal.toFixed(2)}\n`;
    }
    if (discountTotal > 0) {
        text += `🏷️ ${t('label_discount')}: -RM ${discountTotal.toFixed(2)}\n`;
    }

    text += `💰 *${t('total_receipt')} RM ${grandTotal.toFixed(2)}*\n\n`;
    text += `${t('receipt_breakdown_title')}\n`;

    state.people.forEach(p => {
        if (p.debt > 0) {
            text += `👤 *${p.name}*: RM ${p.debt.toFixed(2)}\n`;
        }
    });

    // Check if any payments were recorded
    const totalPaid = state.people.reduce((sum, p) => sum + (p.amountPaid || 0), 0);
    if (totalPaid > 0) {
        text += `\n━━━━━━━━━━━━━━━━━━━━━\n`;
        text += `${t('receipt_payments_title')}\n`;
        state.people.forEach(p => {
            const paid = p.amountPaid || 0;
            const bal = p.balance || 0;
            let balDesc = '';
            if (bal > 0.005) balDesc = ` (+RM ${bal.toFixed(2)} ${t('balance_gets_back')})`;
            else if (bal < -0.005) balDesc = ` (-RM ${Math.abs(bal).toFixed(2)} ${t('balance_owes')})`;
            else balDesc = ` (${t('balance_settled')})`;
            text += `• ${p.name}: RM ${paid.toFixed(2)}${balDesc}\n`;
        });

        const transactions = calculateSettlements(grandTotal);
        text += `\n${t('receipt_settlement_title')}\n`;
        if (transactions.length > 0) {
            transactions.forEach(tr => {
                text += `👉 *${tr.from}* ${t('needs_to_pay')} *${tr.to}* RM ${tr.amount.toFixed(2)}\n`;
            });
        } else {
            text += `${t('receipt_all_settled')}\n`;
        }
    }

    text += `\n_${t('receipt_footer')}_`;
    return text;
}

